export const COUNSEL_CONTENT = Object.freeze(rows.map(([type,variant,title,dialogue,...answers])=>Object.freeze({
  id:`${type}-${variant}`,type,followUp:variant===4,title,dialogue,
  answers:Object.freeze(answers.map(([text,reaction],index)=>Object.freeze({
    id:COUNSEL_PROFILES[index].id,text,reaction,hint:COUNSEL_PROFILES[index].hint,effect:COUNSEL_PROFILES[index].effect,
    ...(index===1 && variant!==4?{followUp:Object.freeze({type,afterMatches:6})}:{}),
  }))),
})));
export const counselContent=id=>COUNSEL_CONTENT.find(content=>content.id===id)??null;

export function chooseCounselContent(seed,counsel,evidence) {
  if(evidence?.source==='follow-up')return `${counsel.type}-4`;
  let hash=(seed^0x6469616c)>>>0;
  for(const char of counsel.id)hash=Math.imul(hash^char.codePointAt(0),16777619)>>>0;
  return `${counsel.type}-${hash%3+1}`;
}
